"""Writes src/stark_vectors.rs: the Stark curve's RFC 6979 nonce vectors.

The key core makes the Stark curve's nonce itself (`keys::stark_nonce`) since
17 November 2026, in place of `starknet-crypto` 0.8.1's `rfc6979_generate_k`,
whose `crypto-bigint` 0.5 is affected by RUSTSEC-2026-0387. These vectors are
what that function was tested with — generated from `cairo-lang`, the
reference — so the nonce, and with it every Starknet signature, is held to be
the same as before:

  - `starknet-crypto/test-data/rfc6979_padded.json` and
    `rfc6979_not_padded.json` of xJonathanLEI/starknet-rs at the tag
    `starknet-crypto/v0.8.1` (commit 85906137d634c86b07de20fa33071e5cf186ce21),
    as GitHub's contents API served them on 17 November 2026 (3,333 bytes
    each; SHA-256
    71f59af0b69ef40d101dc0233a49fcc1f025864ab49a649bd6c7dc2b3ddca30d and
    f0a8dd6c83cc1ae8c284491a5c593c6a404429c3045c212a7d5c283d77f91f93),
    downloaded on the owner's instruction to fix RUSTSEC-2026-0387 and kept
    outside the repository. MIT OR Apache-2.0, as the crate.

Each vector is (message hash, private key, seed, k), 64 hexadecimal digits
each, as the files write them; the crate's tests pass the seed as given, so
these do too.

Usage:
  python3 -I tool/generate_stark_vectors.py <scratch>/rfc6979_padded.json \
      <scratch>/rfc6979_not_padded.json > src/stark_vectors.rs
"""

import json
import re
import sys


def rows(path):
    out = []
    for v in json.load(open(path)):
        row = tuple(v[k] for k in ("msg_hash", "priv_key", "seed", "k"))
        for value in row:
            if not re.fullmatch(r"[0-9a-f]{64}", value):
                raise SystemExit(f"{path}: not 32 bytes of hex: {value}")
        out.append(row)
    return out


def main(padded_path, not_padded_path):
    out = [
        "//! Generated by `tool/generate_stark_vectors.py`; do not edit by hand.",
        "//! Sources and method: that script's docstring.",
        "",
    ]
    for name, path in (("STARK_RFC6979_PADDED", padded_path),
                       ("STARK_RFC6979_NOT_PADDED", not_padded_path)):
        vectors = rows(path)
        out.append("/// cairo-lang's RFC 6979 vectors for the Stark curve, as starknet-rs")
        out.append("/// carries them: (message hash, private key, seed, k)")
        out.append(f"pub(crate) const {name}: [(&str, &str, &str, &str); {len(vectors)}] = [")
        for row in vectors:
            out.append('    ("' + '", "'.join(row) + '"),')
        out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:3])
